// One agent: its character sheet (what code feeds the model), how code schedules it,
// every turn it had, and what it posted.
import Avatar from './Avatar.jsx'
import Post from './Post.jsx'
import { agentStats, displayName, pct, turnsOf } from '../model.js'

const TRAITS = ['attention_seeking', 'agreeableness', 'judgmental', 'curiosity', 'conformity']
const MODE_LABEL = { post: 'post turn', write: 'write turn', react: 'react turn', sleep: 'asleep' }

function Opinion({ label, value }) {
  const left = ((value + 1) / 2) * 100
  return (
    <div className="opinion">
      <div className="olabel">
        <span>{label}</span>
        <span className="muted">{value > 0 ? '+' : ''}{value.toFixed(2)}</span>
      </div>
      <div className="oscale" role="img" aria-label={`${label}: ${value.toFixed(2)} on a scale from -1 against to +1 for`}>
        <span className="omid" />
        <span className="odot" style={{ left: `${left}%` }} />
      </div>
      <div className="oends muted"><span>against</span><span>for</span></div>
    </div>
  )
}

export default function Profile({ run, idx, name, T, onBack, onTurn, onEye, postProps }) {
  const a = run.agents[name]
  if (!a) return <p className="empty muted">No agent {name} in this run.</p>
  const s = agentStats(run, idx, name, T)
  const turns = a.is_news ? [] : turnsOf(run, name, idx.maxTick)
  const seed = run.run.seed_topic || 'NovaCode'

  return (
    <div className="profile">
      <div className="threadbar">
        <button className="ghost" onClick={onBack}>← Feed</button>
        <span className="muted">Profile · as of tick {T}</span>
      </div>

      <header className="phead">
        <Avatar name={name} news={a.is_news} size={64} />
        <div>
          <h2>{a.is_news ? name : displayName(name)}</h2>
          <div className="muted">@{name}</div>
          <div className="tags">
            {a.is_news ? <span className="tag">news account: posts come from config.json</span>
              : <span className="tag">{a.generated ? 'generated by gen_personas.py' : 'hand-written persona'}</span>}
          </div>
        </div>
      </header>
      {a.bio && <p className="pbio">{a.bio}</p>}

      <div className="pstats">
        <div><b>{s.posts}</b><span>posts</span></div>
        <div><b>{s.replies}</b><span>replies</span></div>
        <div><b>{s.likesGiven}</b><span>likes given</span></div>
        <div><b>{s.repliesGot}</b><span>replies received</span></div>
        <div><b>{s.likesGot}</b><span>likes received</span></div>
      </div>

      {!a.is_news && (
        <>
          <section className="pcard">
            <h3>How code schedules {displayName(name)}</h3>
            <div className="odds">
              <div><b>{pct(a.wake_prob)}</b><span>chance to wake each tick</span></div>
              <div><b>{pct(a.write_prob)}</b><span>chance a waking turn is a write turn (+20% if replied to)</span></div>
              <div><b>{pct(a.post_chance)}</b><span>chance to be picked to post each tick</span></div>
            </div>
            <div className="strip" aria-label="Every tick of the run">
              {turns.map((t) => (
                <button
                  key={t.tick}
                  className={`cell m-${t.mode || 'none'} ${t.tick > T ? 'future' : ''}`}
                  title={`tick ${t.tick}: ${MODE_LABEL[t.mode] || 'not recorded'}${t.action?.action ? ` → ${t.action.action}` : ''}`}
                  onClick={() => t.mode && onTurn(`${t.tick}/${name}`)}
                  aria-label={`tick ${t.tick}, ${MODE_LABEL[t.mode] || 'not recorded'}`}
                />
              ))}
            </div>
            <div className="striplegend muted">
              <span><i className="cell m-post" /> post</span>
              <span><i className="cell m-write" /> write</span>
              <span><i className="cell m-react" /> react</span>
              <span><i className="cell m-sleep" /> asleep</span>
              <span>· one square per tick; click one to see that turn</span>
            </div>
          </section>

          <section className="pcard">
            <h3>Character sheet (rendered into the system prompt)</h3>
            <div className="traits">
              {TRAITS.filter((k) => a.traits?.[k] !== undefined).map((k) => (
                <div key={k} className="trait">
                  <span>{k.replace('_', ' ')}</span>
                  <span className="tbar"><span style={{ width: `${a.traits[k] * 100}%` }} /></span>
                  <span className="muted">{a.traits[k].toFixed(2)}</span>
                </div>
              ))}
            </div>
            <h4>Opinions</h4>
            {a.stance !== undefined && a.stance !== null && <Opinion label={seed} value={a.stance} />}
            {Object.entries(a.opinions || {}).map(([k, v]) => <Opinion key={k} label={k} value={v} />)}
            {a.voice && (<><h4>Voice</h4><p className="voice">{a.voice}</p></>)}
            {(a.interests?.length || a.hobbies?.length) ? (
              <>
                <h4>Interests and hobbies</h4>
                <div>
                  {(a.interests || []).map((x) => <span key={x} className="chip">{x}</span>)}
                  {(a.hobbies || []).map((x) => <span key={x} className="chip hobby">{x}</span>)}
                </div>
              </>
            ) : null}
          </section>

          <section className="pcard two">
            <div>
              <h3>Replies most to</h3>
              {s.repliesTo.length ? s.repliesTo.map(([n, c]) => <div key={n} className="kv"><span>@{n}</span><b>{c}</b></div>) : <p className="muted">nobody yet</p>}
            </div>
            <div>
              <h3>Gets replies from</h3>
              {s.repliedBy.length ? s.repliedBy.map(([n, c]) => <div key={n} className="kv"><span>@{n}</span><b>{c}</b></div>) : <p className="muted">nobody yet</p>}
            </div>
          </section>
        </>
      )}

      <h3 className="ptitle">Posts and replies by tick {T}</h3>
      {s.timeline.length ? s.timeline.map((p) => <Post key={p.id} {...postProps} post={p} />)
        : <p className="empty muted">Nothing yet.</p>}
    </div>
  )
}
